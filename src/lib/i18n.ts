export type Dict = typeof dict.pt;

/**
 * Minimal ICU-ish formatting:
 *  - {key} interpolation
 *  - {key, plural, =0 {..} one {..} other {..}} blocks with `#` placeholders
 */
export function format(template: string, vars: Record<string, string | number>): string {
  let out = template.replace(
    /\{(\w+),\s*plural,\s*=0\s*\{([^{}]*)\}\s*one\s*\{([^{}]*)\}\s*other\s*\{([^{}]*)\}\s*\}/g,
    (_m, name: string, zero: string, one: string, other: string) => {
      const n = vars[name];
      if (typeof n !== "number") return "";
      if (n === 0) return zero.replace(/#/g, String(n));
      if (n === 1) return one.replace(/#/g, String(n));
      return other.replace(/#/g, String(n));
    }
  );
  out = out.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
  return out;
}
